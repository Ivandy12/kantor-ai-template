const SKIP_SELECTOR =
  "script,style,code,pre,textarea,input,[contenteditable],[contenteditable=true],.ProseMirror,.cm-editor,.monaco-editor,[data-no-translate],.markdown-body,.prose";
const ATTRS = ["placeholder", "title", "aria-label"];

function terjemah(teks: string): string | null {
  const t = teks.trim();
  if (!t || t.length > 80) return null;
  const hit = KAMUS[t];
  if (hit !== undefined) return hit === t ? null : teks.replace(t, hit);
  for (const [re, fn] of POLA) {
    const m = t.match(re);
    if (m) return teks.replace(t, fn(...m));
  }
  return null;
}

function skip(el: Element | null): boolean {
  return !!el && !!el.closest(SKIP_SELECTOR);
}

function prosesNode(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (!parent || skip(parent)) return;
    const baru = terjemah(node.nodeValue || "");
    if (baru !== null && baru !== node.nodeValue) node.nodeValue = baru;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const el = node as Element;
  if (skip(el)) return;
  for (const a of ATTRS) {
    const v = el.getAttribute(a);
    if (v) {
      const baru = terjemah(v);
      if (baru !== null && baru !== v) el.setAttribute(a, baru);
    }
  }
  const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n: Node | null = walker.nextNode();
  while (n) {
    if (n.nodeType === Node.ELEMENT_NODE) {
      const e = n as Element;
      if (e.matches(SKIP_SELECTOR)) {
        // lompati subtree
        let next: Node | null = e.nextSibling;
        let up: Node | null = e.parentNode;
        while (!next && up && up !== el) {
          next = up.nextSibling;
          up = up.parentNode;
        }
        if (!next) break;
        walker.currentNode = next;
        n = next;
        continue;
      }
      for (const a of ATTRS) {
        const v = e.getAttribute(a);
        if (v) {
          const baru = terjemah(v);
          if (baru !== null && baru !== v) e.setAttribute(a, baru);
        }
      }
    } else {
      prosesNode(n);
    }
    n = walker.nextNode();
  }
}

